import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const cav2Root = resolve(packageRoot, "..");
const projectsRoot = resolve(cav2Root, "..", "..");
const target = resolve(packageRoot, "../workspace/runtime/src/domain/foundation-capability-instance.generated.ts");
const readJson = async (name) => JSON.parse(await readFile(join(packageRoot, name), "utf8"));
const sha256File = async (path) => createHash("sha256").update(await readFile(path)).digest("hex");

const [profile, sources, definitions, artifactTypes, relations, candidate, composition] = await Promise.all([
  readJson("profile.json"),
  readJson("sources.json"),
  readJson("definitions/candidate-pack.json"),
  readJson("artifact-types.json"),
  readJson("identity-relations.json"),
  readJson("candidate.json"),
  readJson("composition.json"),
]);

const projection = {
  schema: "cav2.workspace-capability-instance-projection/v1",
  generated_from: "cyberAlchemy-v2/foundation",
  profile,
  capability_instance: candidate,
  lab_definition_bindings: sources.definitions,
  source_currentness: {
    status: "current-at-generation",
    checked_count: sources.definitions.length + sources.local_bindings.length,
  },
  local_definition_candidates: definitions.definitions,
  artifact_type_candidates: artifactTypes.artifact_types,
  identity_relations: relations.relations,
  composition_layers: composition.layers,
  runtime: {
    preflight_available: true,
    effectful_invocation_available: false,
    host_receipt_available: false,
  },
  claim_ceiling: "generated Workspace projection of an effect-free product candidate",
};

for (const source of sources.definitions) {
  const actual = await sha256File(join(projectsRoot, source.repository, source.path));
  if (actual !== source.sha256) throw new Error(`FOUNDATION_SOURCE_DRIFT:${source.term}`);
}
for (const binding of sources.local_bindings) {
  const actual = await sha256File(join(cav2Root, binding.path));
  if (actual !== binding.sha256) throw new Error(`FOUNDATION_LOCAL_BINDING_DRIFT:${binding.path}`);
}

const output = `// Generated by cyberAlchemy-v2/foundation/scripts/build-workspace-projection.mjs.\n// Do not edit by hand.\nexport const foundationCapabilityInstanceProjection = ${JSON.stringify(projection, null, 2)} as const;\n`;

if (process.argv.includes("--check")) {
  let actual = null;
  try { actual = await readFile(target, "utf8"); } catch { /* missing is drift */ }
  if (actual !== output) {
    process.stderr.write(`Foundation Workspace projection is stale: ${target}\n`);
    process.exitCode = 1;
  }
} else {
  await writeFile(target, output);
  process.stdout.write(`${target}\n`);
}
