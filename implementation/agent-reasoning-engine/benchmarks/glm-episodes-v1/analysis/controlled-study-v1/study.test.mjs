// Offline treatment contract checks. Open questions: README.md#open-questions.
import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {arms,decorateRequest,normalizeSubmission} from './treatments.mjs';
import {schedule} from './prepare.mjs';
import {submissionTool} from '../../../../packages/coding-agent-runtime/glm-flash-v1/submission.mjs';
const base={tree_sha256:'a'.repeat(64),files:{'subject.mjs':'b'.repeat(64)}},paths=['subject.mjs'];
const candidate={schema_version:'are.patch-set-candidate/v1',authority_effect:'none',expected_base_tree_sha256:base.tree_sha256,changes:[{operation:'replace-file',path:paths[0],expected_file_sha256:base.files[paths[0]],utf8:'export const x=2;'}]};
const body={messages:[{role:'system',content:'Synthetic baseline'}],tools:[submissionTool(base,paths)]};
const normalized=(value,arm)=>normalizeSubmission(JSON.stringify(value),{arm,base,paths});
test('baseline and reading turns remain unchanged; decoration never mutates its input',()=>{
 assert.deepEqual(decorateRequest(body,{arm:'baseline',family:'archive'}),body);
 const original=structuredClone(body);decorateRequest(body,{arm:'metadata-card',family:'archive'});assert.deepEqual(body,original);
 const reading={messages:body.messages,tools:[]};for(const arm of arms)assert.deepEqual(decorateRequest(reading,{arm,family:'archive'}),reading);
});
test('host envelope changes only two schema fields and preserves exact code/scope on normalization',()=>{
 const value=structuredClone(candidate);delete value.schema_version;delete value.authority_effect;
 const r=normalized(value,'host-envelope');assert.equal(r.ok,true);assert.deepEqual(JSON.parse(JSON.stringify(r.value)),candidate);assert.equal(r.model_envelope_field_fidelity,null);assert.equal(r.raw_full_contract_valid,false);
 const tool=decorateRequest(body,{arm:'host-envelope',family:'archive'}).tools[0];
 assert.deepEqual(tool.function.parameters.properties.changes,body.tools[0].function.parameters.properties.changes);
 assert.deepEqual(tool.function.parameters.required,['expected_base_tree_sha256','changes']);
});
test('host cannot override malicious authority, broaden scope, repair missing code or swallow extras',()=>{
 for(const mutate of [v=>v.authority_effect='apply',v=>v.schema_version='wrong',v=>v.changes[0].path='../outside',v=>v.expected_base_tree_sha256='c'.repeat(64),v=>delete v.changes[0].utf8,v=>v.extra=true]){
  const v=structuredClone(candidate);delete v.schema_version;delete v.authority_effect;mutate(v);assert.equal(normalized(v,'host-envelope').ok,false);
 }
});
test('full-contract arms never auto-fill missing metadata',()=>{
 for(const arm of arms.filter(a=>a!=='host-envelope')){assert.equal(normalized(candidate,arm).ok,true);const v=structuredClone(candidate);delete v.schema_version;assert.equal(normalized(v,arm).ok,false);}
});
test('schedule has complete paired blocks, balanced positions and fixed physical caps',()=>{
 const rows=schedule();assert.equal(rows.length,120);assert.equal(new Set(rows.map(r=>r.id)).size,120);
 for(let b=0;b<24;b++)assert.deepEqual(rows.filter(r=>r.block===b).map(r=>r.arm).sort(),[...arms].sort());
 for(const arm of arms){const counts=Array.from({length:5},(_,i)=>rows.filter(r=>r.arm===arm&&r.position===i).length);assert.ok(Math.max(...counts)-Math.min(...counts)<=1);}
 assert.equal(rows.reduce((n,r)=>n+r.maximum_model_attempts,0),1600);assert.equal(rows.reduce((n,r)=>n+r.maximum_tokenizer_attempts,0),3200);
});
test('retained preparation binds generated bytes and source bytes',()=>{
 const manifest=JSON.parse(readFileSync(new URL('prepared/manifest.json',import.meta.url)));
 const sha=b=>createHash('sha256').update(b).digest('hex');
 for(const s of manifest.files)assert.equal(sha(readFileSync(new URL('prepared/'+s.path,import.meta.url))),s.sha256,s.path);
 for(const s of manifest.source_hashes)assert.equal(sha(readFileSync(new URL(s.path,import.meta.url))),s.sha256,s.path);
 assert.ok(manifest.validation.every(v=>v.reference_passed===6&&v.mutant_failures>0&&v.old_exact_cases_reused===0));
});
