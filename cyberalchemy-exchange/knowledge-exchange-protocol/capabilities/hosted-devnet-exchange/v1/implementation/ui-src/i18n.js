export function translate(value) {
  const source = String(value ?? "");
  if (!isPortuguese) return source;
  const exact = ptBR.get(source);
  if (exact) return exact;
  for (const [pattern, replacement] of ptPatterns) {
    if (pattern.test(source)) return source.replace(pattern, replacement);
  }
  return source;
}

function translateNode(node) {
  const parent = node.parentElement;
  if (!parent || parent.closest("script, style, code, pre, [data-no-i18n], .knowledge-result")) return;
  const raw = node.nodeValue || "";
  const trimmed = raw.trim();
  if (!trimmed) return;
  const translated = translate(trimmed);
  if (translated === trimmed) return;
  const start = raw.slice(0, raw.indexOf(trimmed));
  const end = raw.slice(raw.indexOf(trimmed) + trimmed.length);
  node.nodeValue = `${start}${translated}${end}`;
}

export function localize(root = document.body) {
  if (!isPortuguese || !root) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach(translateNode);
  const elements = root.matches?.("[aria-label], [placeholder], [title]") ? [root] : [];
  elements.push(...root.querySelectorAll?.("[aria-label], [placeholder], [title]") || []);
  for (const element of elements) {
    for (const attribute of ["aria-label", "placeholder", "title"]) {
      if (element.hasAttribute(attribute)) element.setAttribute(attribute, translate(element.getAttribute(attribute)));
    }
  }
}

export function setLocale(nextLocale) {
  const url = new URL(window.location.href);
  if (nextLocale === "pt-BR") url.searchParams.set("lang", "pt-BR");
  else url.searchParams.delete("lang");
  window.location.assign(url.toString());
}

export function initializeLocale() {
  document.documentElement.lang = locale;
  if (isPortuguese) {
    document.title = translate(document.title);
    const description = document.querySelector('meta[name="description"]');
    if (description) description.content = translate(description.content);
    localize(document.body);
  }
  document.querySelectorAll("[data-locale-select]").forEach((control) => {
    control.value = locale;
    control.addEventListener("change", () => setLocale(control.value));
  });
  document.querySelectorAll("[data-locale-flag]").forEach((flag) => {
    flag.src = isPortuguese ? "/assets/flag-br.svg" : "/assets/flag-us.svg";
  });
}
