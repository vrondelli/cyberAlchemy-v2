#!/usr/bin/env python3
"""Validate the exact Knowledge Exchange Protocol system-ontology admission."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any


PACKAGE_ROOT = Path(__file__).resolve().parent.parent
FILES = {
    "graph": "domainspec/generated/graph.json",
    "system_ontology": "domainspec/generated/system-ontology.json",
    "projection_receipt": "domainspec/generated/system-ontology-receipt.json",
    "candidate": "domainspec/generated/system-ontology-admission-candidate.json",
    "construction_binding": "domainspec/construction-binding.json",
    "decision": "decisions/system-ontology-admission.json",
}


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read_json(relative_path: str) -> dict[str, Any]:
    return json.loads((PACKAGE_ROOT / relative_path).read_text(encoding="utf-8"))


def stable_digest(value: Any) -> str:
    data = json.dumps(value, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(data).hexdigest()


def validate(require_decision: bool) -> dict[str, Any]:
    errors: list[str] = []
    checks: list[dict[str, str]] = []

    def check(check_id: str, condition: bool, error: str) -> None:
        checks.append({"check_id": check_id, "status": "PASS" if condition else "FAIL"})
        if not condition:
            errors.append(f"{check_id}:{error}")

    loaded: dict[str, dict[str, Any]] = {}
    actual_digests: dict[str, str] = {}
    for name, relative_path in FILES.items():
        if name == "decision" and not require_decision:
            continue
        path = PACKAGE_ROOT / relative_path
        if not path.is_file():
            errors.append(f"file-present:{relative_path}:missing")
            loaded[name] = {}
            actual_digests[name] = "missing"
            continue
        try:
            loaded[name] = read_json(relative_path)
            actual_digests[name] = digest(path)
        except (OSError, json.JSONDecodeError) as exc:
            errors.append(f"file-readable:{relative_path}:{exc}")
            loaded[name] = {}
            actual_digests[name] = "unreadable"

    graph = loaded.get("graph", {})
    system_ontology = loaded.get("system_ontology", {})
    receipt = loaded.get("projection_receipt", {})
    candidate = loaded.get("candidate", {})
    binding = loaded.get("construction_binding", {})

    check("candidate-id", candidate.get("candidate_id") == "CA2-CANDIDATE-KEP-SYSTEM-ONTOLOGY-001", "unexpected candidate")
    check("ontology-id", candidate.get("ontology_id") == "knowledge-exchange.system.encrypted-coownership", "unexpected ontology")
    check("graph-digest", candidate.get("source_graph_digest") == actual_digests.get("graph"), "candidate does not bind graph bytes")
    check("system-ontology-digest", candidate.get("system_ontology_digest") == actual_digests.get("system_ontology"), "candidate does not bind system ontology bytes")
    check("construction-binding-digest", candidate.get("construction_binding_digest") == actual_digests.get("construction_binding"), "candidate does not bind construction bytes")
    check("receipt-graph-digest", receipt.get("source_graph_digest") == actual_digests.get("graph"), "receipt graph drift")
    check("receipt-system-ontology-digest", receipt.get("system_ontology_digest") == actual_digests.get("system_ontology"), "receipt ontology drift")
    check("receipt-construction-binding-digest", receipt.get("construction_binding_digest") == actual_digests.get("construction_binding"), "receipt construction drift")
    check("deterministic-graph", receipt.get("deterministic_runs") == 2 and receipt.get("equal_graph_bytes") is True, "two equal graph runs not proven")
    check("deterministic-system-ontology", receipt.get("deterministic_runs") == 2 and receipt.get("equal_system_ontology_bytes") is True, "two equal ontology runs not proven")
    check("predecessor-verification", receipt.get("predecessor_verification") == "pass", "predecessor verification did not pass")
    check("semantic-coverage", receipt.get("semantic_coverage") == "closed" and system_ontology.get("semantic_coverage", {}).get("status") == "closed", "semantic coverage is open")
    check("candidate-lifecycle", system_ontology.get("lifecycle_status") == "candidate", "generated bytes must remain candidate evidence")
    check("candidate-effect-ceiling", system_ontology.get("authority_effect") == "none" and system_ontology.get("enforcement_effect") == "none", "generated candidate claims authority")
    check("source-project", graph.get("project_id") == "knowledge-exchange-protocol" and system_ontology.get("source_project_id") == graph.get("project_id"), "project identity mismatch")
    check("graph-binding", system_ontology.get("source_graph_digest") == actual_digests.get("graph"), "system ontology does not bind graph")
    check("predecessor-binding-copy", candidate.get("predecessor_bindings") == binding.get("predecessors") == system_ontology.get("predecessor_bindings"), "predecessor bindings differ")

    predecessors = binding.get("predecessors", {})
    for predecessor_name in ("canonical_definitions", "product_capability", "business_ontology", "admission_decision"):
        predecessor = predecessors.get(predecessor_name, {})
        relative_path = predecessor.get("path")
        path = PACKAGE_ROOT / relative_path if isinstance(relative_path, str) else None
        current = digest(path) if path and path.is_file() else "missing"
        check(f"predecessor-current-{predecessor_name}", current == predecessor.get("sha256"), f"expected {predecessor.get('sha256')} got {current}")

    node_ids = {node.get("node_id") for node in graph.get("nodes", [])}
    check("reissue-request-modeled", "encrypted-knowledge-coownership.KeyReissueRequest" in node_ids, "request node missing")
    check("reissue-result-modeled", "encrypted-knowledge-coownership.KeyReissue" in node_ids, "reissue result node missing")
    authored_refs = set(system_ontology.get("semantic_coverage", {}).get("authored_semantic_refs", []))
    check("ciphertext-reference-current", "CA2-CONTENT-ADDRESSED-CIPHERTEXT-REFERENCE" in authored_refs and "CA2-CONTENT-ADDRESSED-CIPHERTEXT-LOCATION" not in authored_refs, "ciphertext reference is stale")
    contract = system_ontology.get("implementation_contract", {})
    check("implementation-blocked", contract.get("implementation_binding_status") == "blocked-pending-system-ontology-admission" and contract.get("effect_authorized") is False, "implementation was implicitly authorized")
    check("candidate-request", candidate.get("requested_decision") == "admit-system-ontology" and candidate.get("requested_successor_authorization") == "none", "candidate requests a broader effect")

    material = {name: actual_digests.get(name) for name in ("graph", "system_ontology", "projection_receipt", "candidate", "construction_binding")}
    material_digest = stable_digest(material)

    if require_decision:
        decision = loaded.get("decision", {})
        admitted = decision.get("admitted_artifacts", {})
        check("decision-id", decision.get("decision_id") == "CA2-DECISION-KEP-SYSTEM-ONTOLOGY-ADMISSION-001", "unexpected decision id")
        check("decision-source", decision.get("source", {}).get("exact_user_decision") == "Continue", "decision source is not exact")
        check("decision-candidate", decision.get("candidate", {}).get("candidate_id") == candidate.get("candidate_id") and decision.get("candidate", {}).get("sha256") == actual_digests.get("candidate"), "decision does not bind candidate")
        for name in ("graph", "system_ontology", "projection_receipt", "construction_binding"):
            check(f"decision-binds-{name}", admitted.get(name, {}).get("sha256") == actual_digests.get(name), f"decision {name} digest drift")
        check("decision-preacceptance", decision.get("preacceptance", {}).get("material_digest") == material_digest and decision.get("preacceptance", {}).get("outputs_identical") is True, "preacceptance binding mismatch")
        check("decision-admission", decision.get("admission", {}).get("lifecycle_status") == "admitted" and decision.get("admission", {}).get("system_ontology_digest") == actual_digests.get("system_ontology"), "system ontology not admitted exactly")
        check("decision-successor-ceiling", decision.get("successor_authorization") == "none" and decision.get("enforcement_effect") == "none" and decision.get("external_effect") == "none", "decision grants successor effect")

    return {
        "schema_version": "knowledge-exchange-protocol-system-ontology-admission-validation/v1",
        "mode": "admitted" if require_decision else "preacceptance",
        "status": "PASS" if not errors else "FAIL",
        "candidate_id": candidate.get("candidate_id"),
        "ontology_id": candidate.get("ontology_id"),
        "source_graph_digest": actual_digests.get("graph"),
        "system_ontology_digest": actual_digests.get("system_ontology"),
        "material_digest": material_digest,
        "checks": checks,
        "errors": errors,
        "authority_effect": "none",
        "claim_ceiling": "Admission validation only; no implementation binding, conformance, cryptographic security, Solana realization, publication, release, deployment, or external effect.",
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--admitted", action="store_true", help="Require and validate the immutable admission decision")
    args = parser.parse_args()
    report = validate(args.admitted)
    print(json.dumps(report, indent=2, sort_keys=True))
    return 0 if report["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
