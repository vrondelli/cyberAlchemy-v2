"""Discovery-specific browser checks. No live payment or delivery is attempted."""
from pathlib import Path
import json,re
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parent
HTML=(ROOT/'keld-shop-standalone.html').read_text()
PRE=ROOT/'previews'; PRE.mkdir(exist_ok=True)
checks=[]; errors=[]
def ck(name, condition):
 checks.append({'test':name,'passed':bool(condition)})
 print(('PASS ' if condition else 'FAIL ')+name,flush=True)
def opened(q):return q.locator('#hidden-shelf').is_visible()
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True,args=['--no-sandbox','--disable-dev-shm-usage'])
 def page(width=1440,height=1150,**kwargs):
  q=browser.new_page(viewport={'width':width,'height':height},**kwargs)
  q.on('pageerror',lambda e:errors.append(str(e)))
  q.set_default_timeout(5000);q.set_content(HTML,wait_until='load');return q
 def fresh():return page()
 q=fresh()
 ck('Fresh page starts at $200 and slider starts at $200',q.locator('#custom-price').input_value()=='200' and q.locator('#price-slider').get_attribute('min')=='200')
 ck('Only $200, $500, $1,000 presets are visible',q.locator('[data-price-preset]:visible').all_text_contents()==['$200','$500','$1,000'])
 ck('Secret region is hidden',not opened(q))
 ck('No lower prices in initial accessible tree',not re.search(r'\$(?:50|100)(?!\d)',q.locator('body').aria_snapshot()))
 ck('Amount field does not announce secret minimum before discovery',q.locator('#custom-price').get_attribute('min') is None)
 q.wait_for_timeout(450);q.screenshot(path=str(PRE/'shop-desktop.png'))
 q.locator('.price-choice').screenshot(path=str(PRE/'pricing-before.png'))
 for amount in ['500','1000','250','200']:
  q.locator('#custom-price').fill('')
  q.locator('#custom-price').press_sequentially(amount,delay=35)
  ck('Typing '+amount+' does not unlock on intermediate digits',not opened(q))
  q.locator('#custom-price').press('Tab')
  ck('Committing '+amount+' keeps secret hidden',not opened(q))
 q.locator('#price-slider').press('Home')
 ck('Home at visible minimum is not a lower attempt',not opened(q) and q.locator('#custom-price').input_value()=='200')
 q.locator('#price-increase').click();ck('Increasing above base does not reveal',not opened(q) and q.locator('#custom-price').input_value()=='225')
 q.locator('#price-decrease').click();ck('Returning to exactly base does not reveal',not opened(q) and q.locator('#custom-price').input_value()=='200')
 q.locator('#price-decrease').click()
 ck('Minus at base reveals and chooses $175',opened(q) and q.locator('#custom-price').input_value()=='175')
 ck('Lower presets become available',q.locator('#hidden-price-presets button:visible').all_text_contents()==['$50','$100'])
 ck('Slider expands to true $50 minimum',q.locator('#price-slider').get_attribute('min')=='50')
 ck('Discovery does not steal focus',q.locator('#price-decrease').evaluate('(el)=>el===document.activeElement'))
 ck('Announcement contains discoverable lower floor', '$50' in q.locator('#shop-status').text_content() or q.locator('#hidden-shelf').is_visible())
 q.locator('[data-price-preset="10000"]').click()
 q.wait_for_timeout(500);q.evaluate('window.scrollTo(0,0)');q.screenshot(path=str(PRE/'shop-desktop-revealed.png'))
 q.locator('.price-choice').screenshot(path=str(PRE/'pricing-after.png'))
 q.locator('#reset-price').click();ck('Reset returns to base without forgetting discovery',opened(q) and q.locator('#custom-price').input_value()=='200')
 q.locator('#price-slider').press('Home');ck('Home selects $50 after discovery',q.locator('#custom-price').input_value()=='50')
 ck('Minus disables at actual floor',q.locator('#price-decrease').is_disabled())
 q.close()
 q=fresh();q.locator('#custom-price').fill('100');ck('Lower typed draft waits for commitment',not opened(q))
 q.locator('#custom-price').press('Tab');ck('Tab confirms lower price and reveals',opened(q) and q.locator('#custom-price').input_value()=='100');q.close()
 q=fresh();q.locator('#custom-price').fill('50');q.locator('#custom-price').press('Enter')
 ck('Enter lower price reveals and adds to bag',opened(q) and q.locator('#shop-bag-dialog').is_visible() and q.locator('.bag-total [data-bag-price]').inner_text()=='$50');q.close()
 q=fresh();q.locator('#custom-price').fill('99.99');q.locator('#add-to-bag').click()
 ck('Clicking Add after lower draft is not lost to reveal layout shift',q.locator('#shop-bag-dialog').is_visible() and q.locator('#bag-price').input_value()=='99.99' and opened(q));q.close()
 q=fresh();q.locator('#custom-price').fill('49.99');q.locator('#custom-price').press('Tab')
 ck('Below true floor reveals but remains invalid',opened(q) and q.locator('#add-to-bag').is_disabled() and '$50' in q.locator('#price-error').inner_text());q.close()
 q=fresh();q.locator('#custom-price').fill('1001');q.locator('#custom-price').press('Tab')
 ck('Above maximum is rejected without revealing secret',not opened(q) and q.locator('#add-to-bag').is_disabled() and '$50' not in q.locator('#price-error').inner_text());q.close()
 q=fresh();q.locator('#price-slider').press('ArrowLeft')
 ck('Slider ArrowLeft at base reveals',opened(q) and q.locator('#custom-price').input_value()=='199');q.close()
 q=fresh();q.locator('#custom-price').press('ArrowDown')
 ck('Amount field ArrowDown at base reveals',opened(q) and q.locator('#custom-price').input_value()=='199');q.close()
 q=fresh();q.locator('#price-slider').press('PageDown')
 ck('Slider PageDown below base reveals',opened(q) and q.locator('#custom-price').input_value()=='150');q.close()
 q=fresh();box=q.locator('#price-slider').bounding_box();x=box['x']+8.5;y=box['y']+box['height']/2
 q.mouse.move(x,y);q.mouse.down();q.mouse.up();ck('Tapping slider base alone does not reveal',not opened(q))
 q.mouse.move(x,y);q.mouse.down();q.mouse.move(x-20,y,steps=6);q.mouse.up()
 ck('Dragging left past $200 reveals lower range',opened(q) and 50<=float(q.locator('#custom-price').input_value())<200)
 q.close()
 q=fresh();q.locator('#add-to-bag').click()
 ck('Bag at base does not expose lower prices',not q.locator('#bag-secret-note').is_visible() and '$50' not in q.locator('#bag-filled').inner_text())
 q.locator('#bag-price').fill('125.25');q.locator('#review-checkout').click()
 ck('Bag lower-price commit opens checkout in one click',q.locator('#shop-checkout-dialog').is_visible())
 ck('Checkout carries exact discovered cents',q.locator('.checkout-summary-total [data-bag-price]').inner_text()=='$125.25')
 ck('Checkout states pending license terms',q.locator('.checkout-summary [data-bag-license]').inner_text()=='Terms pending')
 q.screenshot(path=str(PRE/'shop-secret-checkout.png'));q.close()
 for width in [320,375,390,428,768,1024,1440,1920]:
  q=page(width,1000)
  if width==390:
   q.locator('.price-choice').scroll_into_view_if_needed();q.wait_for_timeout(300)
   q.screenshot(path=str(PRE/'shop-mobile-before.png'))
  q.locator('#price-decrease').click();q.wait_for_timeout(450)
  ck('Revealed state no horizontal overflow at '+str(width),q.evaluate('document.documentElement.scrollWidth<=innerWidth+1'))
  if width==390:
   q.locator('[data-price-preset="10000"]').click()
   q.locator('.price-choice').scroll_into_view_if_needed();q.wait_for_timeout(300)
   q.screenshot(path=str(PRE/'shop-mobile-revealed.png'))
   q.locator('.price-choice').screenshot(path=str(PRE/'pricing-mobile-revealed.png'))
  q.close()
 q=page(390,900,is_mobile=True,has_touch=True)
 q.locator('#price-decrease').tap();ck('Touch minus reveals on mobile',opened(q) and q.locator('#custom-price').input_value()=='175')
 q.locator('[data-price-preset="5000"]').tap();q.locator('#add-to-bag').tap();ck('Touch discovered $50 reaches the bag',q.locator('.bag-total [data-bag-price]').inner_text()=='$50');q.close()
 q=page(reduced_motion='reduce');q.locator('#price-decrease').click()
 ck('Reduced-motion reveal is instant',opened(q) and q.locator('#hidden-shelf').evaluate('el=>getComputedStyle(el).animationName')=='none');q.close()
 ck('No browser JavaScript errors',not errors)
 browser.close()
(ROOT/'QA-discovery.json').write_text(json.dumps({'checks':checks,'errors':errors,'scope':'Local Chromium, desktop, keyboard and mobile emulation. No live payment or fulfillment tested.'},indent=2))
failed=[x['test'] for x in checks if not x['passed']]
if failed:raise SystemExit('Failed: '+', '.join(failed))
print('All '+str(len(checks))+' discovery checks passed.')
