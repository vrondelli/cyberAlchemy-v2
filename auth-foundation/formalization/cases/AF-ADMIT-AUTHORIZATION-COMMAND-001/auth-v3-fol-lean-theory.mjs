import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { renderFolTheory } from './auth-v2-fol-lean-theory.mjs';
import { checkCurrentAuthV3TypedMeaning } from './auth-v3-typed-meaning.mjs';

// Reuse the pinned FOL AST renderer without changing historical V2 evidence.
// Only the translation envelope differs; the renderer still parses all six
// clause sources and checks the complete signature before emitting Lean.
export function renderFolTheoryV3(source) {
  assert.equal(source.schema_version,
    'auth-foundation.command-boundary-fol-translation/v2-typed-definitions-candidate');
  assert.equal(source.status, 'draft-typed-translation-not-current-claim');
  assert.equal(source.authority_effect, 'none');
  const adapted = {
    ...source,
    schema_version: 'auth-foundation.command-boundary-fol-translation/v1-candidate',
    status: 'draft-translation-not-current-claim',
  };
  return renderFolTheory(adapted)
    .replace('GENERATED by auth-v2-fol-lean-theory.mjs',
      'GENERATED by auth-v3-fol-lean-theory.mjs via pinned V2 AST renderer')
    .replaceAll('AuthFolGeneratedTheory', 'AuthFolGeneratedTheoryV3');
}

if (process.argv[1] && import.meta.url === new URL(`file://${process.argv[1]}`).href) {
  checkCurrentAuthV3TypedMeaning();
  const source = JSON.parse(readFileSync(new URL('./AUTH-V3-FOL-TRANSLATION.v1-candidate.json', import.meta.url)));
  process.stdout.write(renderFolTheoryV3(source));
}
