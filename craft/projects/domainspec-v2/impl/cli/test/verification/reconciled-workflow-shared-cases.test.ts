import assert from 'node:assert/strict';
import test from 'node:test';
import {workflowFixture} from '../helpers/workflow-verification.ts';
import {workflowValuesFixture, named} from '../helpers/workflow-values.ts';
import {planCompiledReconciledPythonProject, getPythonWorkflowVerificationContext} from '../../src/generation/reconciled-python-project.ts';
import {RECONCILED_PYTHON_COMPILATION_VERSION, RECONCILED_PYTHON_PROFILE} from '../../src/generation/reconciled-python-selection.ts';
import {createBoundWorkflowExecutionReference} from '../../src/verification/reconciled-workflow-execution-reference.ts';
import {createWorkflowSemanticCases} from '../../src/verification/reconciled-workflow-cases.ts';
import {workflowVerificationDefinitions} from '../../src/verification/reconciled-workflow-controls.ts';
import {createPythonOwnedValueContext} from '../../src/verification/reconciled-python-value-context.ts';
import {canonicalJson, sha256} from '../../src/input/source-manifest.ts';

// Captured from the unchanged TypeScript source oracle and Python planner before
// extracting the shared seam. These tests never build a TypeScript project.
const baselines = [
  {id: 'scalar', suite: '6e1c9dfc87a4081aa1a9fbe8785a75e4783f3786e8a0ade040971c5ae8c99767', plan: 'b9b79dc5b9f31f8f38fd94364772bf18dbdc217338f4ae2a53f6d88abf79150b', artifacts: '545c63b2634e33d40d4cb333ec657b96b9bf87a98016c3184c8ec0361d493d1a', count: 133},
  {id: 'constrained', suite: 'd5fc75562c08cccb5cc3c6a0eef89826eaf02f4b0f46f05091ea42a2d233f5af', plan: '098538375b27fdb933966634875876c1a859590e0ae291757c5cabd2a30e5893', artifacts: 'd8253ad3a53dc4693359f523eb42ced6eb3e87c05a6bd819372fb2a661a7da7c', count: 133},
  {id: 'no-compensations', suite: '5111e0ab840c6274b5b8cb326b0dfb3f32100b69af533b72ed2d00b72445c2e9', plan: 'b67a6950e53d3551ef171ab6eea31ebef4a39471a75a7efdc3fd244178c1dcac', artifacts: '27d2c879d37f2d46f0e30b6bce159fe8bc490b290fc950fe3ff968c81e940710', count: 133},
  {id: 'owned-events', suite: 'ba35fbc0dae5944ee5ec8b4205812adf469c53e2429cb758d17f19c9b89f851d', plan: '9338c3acdfab5154423d38a0f534931e6e03bbf7a68f319053ea580d1d51d308', artifacts: 'e7073a3a09452c5397fa8604d92a70eb2b43d62cbca86687af28e2586bdf6ef1', count: 396}
] as const;

for (const baseline of baselines) test('native Workflow preparation preserves complete source suite and generated bytes: ' + baseline.id, t => {
  const f = baseline.id === 'owned-events' ? workflowValuesFixture(t, {type: named('customer'), events: true}) : workflowFixture(t,
    baseline.id === 'constrained' ? {dependencies: [[], ['undo-first'], ['undo-second']]} : baseline.id === 'no-compensations' ? {noCompensations: true} : {});
  const selected = f.selection;
  const plan = planCompiledReconciledPythonProject(f.graph, {schema_version: RECONCILED_PYTHON_COMPILATION_VERSION,
    profile_id: RECONCILED_PYTHON_PROFILE, language: 'python', module_root: selected.module_root, layout_version: selected.layout_version,
    field_bindings: selected.field_bindings, factories: selected.factories, operations: selected.operations, workflows: selected.workflows});
  // Plan identity includes the source capsule, which future verified additions
  // may change. The unchanged generated artifacts remain independently pinned.
  assert.equal(sha256(canonicalJson(plan.artifacts)), baseline.artifacts);
  const before = canonicalJson(plan), context = getPythonWorkflowVerificationContext(plan);
  assert.equal(context.length, 1); assert.ok(Object.isFrozen(context));
  assert.throws(() => getPythonWorkflowVerificationContext(structuredClone(plan)), /registered Python/);
  assert.equal(canonicalJson(context).includes('"artifacts"'), false);
  assert.equal(canonicalJson(context).includes('"content"'), false);
  const {workflow, policy, actions, modules} = context[0]!;
  const request = plan.requests.find(r => r.kind === 'workflow')!.selection as any;
  assert.equal(workflow, request.workflow); assert.equal(policy, request.policy); assert.equal(policy.workflow, workflow);
  assert.deepEqual(actions, request.actions);
  assert.equal(modules[0]!.descriptor.workflow_sha256, workflow.workflow_sha256);
  assert.equal(modules[0]!.descriptor.policy_sha256, policy.policy_sha256);
  const d = workflowVerificationDefinitions(), definitions = {execution: d.execution, values: d.values, outcomes: d.outcomes};
  const oracle = createBoundWorkflowExecutionReference(f.graph, workflow, policy, actions, selected.factories, definitions);
  const suite = createWorkflowSemanticCases(f.graph, oracle, selected.factories, selector => createPythonOwnedValueContext(selector, f.graph, plan), d.cases);
  assert.equal(suite.cases.length, baseline.count);
  assert.equal(sha256(canonicalJson(suite)), baseline.suite);
  assert.deepEqual(workflow.steps.map(s => s.step_id), ['first', 'second', 'third', 'last']);
  assert.equal(new Set(workflow.steps.map(s => s.operation_ref)).size, 1);
  for (const step of workflow.steps) assert.ok(suite.coverage['settlement/' + step.step_id + '/rejected']);
  assert.ok(Object.isFrozen(suite.cases) && Object.isFrozen(suite.coverage));
  assert.equal(canonicalJson(plan), before, 'context access and preparation do not change serialized plan');
  t.diagnostic(JSON.stringify({cases: suite.cases.length, dimensions: Object.keys(suite.coverage).length, suite_sha256: baseline.suite, artifacts_sha256: baseline.artifacts}));

  if (baseline.id !== 'scalar') return;
  const build = (g = f.graph, w = workflow, p = policy, a = actions, defs = definitions) => createBoundWorkflowExecutionReference(g, w, p, a, selected.factories, defs);
  assert.throws(() => build(structuredClone(f.graph)), /unvalidated/i);
  assert.throws(() => build(f.graph, structuredClone(workflow)), /UNVALIDATED/);
  assert.throws(() => build(f.graph, workflow, structuredClone(policy)), /unvalidated policy/);
  assert.throws(() => build(f.graph, workflow, policy, actions.map(a => structuredClone(a))), /UNVALIDATED/);
  assert.throws(() => build(f.graph, workflow, policy, actions.slice(1)), /exact action closure/);
  assert.throws(() => build(f.graph, workflow, policy, actions.map(() => actions[0]!)), /source action binding/);
  assert.throws(() => build(f.graph, workflow, policy, actions, {...definitions, execution: d.execution + '\n'}), /definition drift/);
  let reads = 0; const active = [...actions];
  Object.defineProperty(active, '0', {enumerable: true, get() {reads++; return actions[0];}});
  assert.throws(() => build(f.graph, workflow, policy, active), /inert source action/); assert.equal(reads, 0);
  const foreign = workflowFixture(t);
  assert.throws(() => build(f.graph, workflow, foreign.policy), /source Workflow\/policy identity/);
});
