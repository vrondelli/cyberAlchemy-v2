import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const graphPath = resolve(root, "domainspec/generated/graph.json");
const receiptPath = resolve(root, "domainspec/generated/build-receipt.json");
const contentPath = resolve(root, "content/game-content.json");
const outputPath = resolve(root, "web/runtime-model.js");

const graphBytes = readFileSync(graphPath, "utf8");
const graph = JSON.parse(graphBytes);
const receipt = JSON.parse(readFileSync(receiptPath, "utf8"));
const contentBytes = readFileSync(contentPath, "utf8");
const content = JSON.parse(contentBytes);
const nodeIds = new Set(graph.nodes.map((node) => node.node_id));
const missing = content.required_system_nodes.filter((id) => !nodeIds.has(id));

if (missing.length > 0) {
  throw new Error(`RUNTIME_BINDING_NODE_MISSING:${missing.join(",")}`);
}

const graphDigest = sha256(graphBytes);
const declaredGraphDigest = String(receipt.graph_digest ?? "").replace(/^sha256:/, "");
if (declaredGraphDigest && declaredGraphDigest !== graphDigest) {
  throw new Error(`RUNTIME_BINDING_GRAPH_DIGEST_MISMATCH:${declaredGraphDigest}:${graphDigest}`);
}

const model = {
  schema_version: "bug-ticket-ontology-game-runtime/v0.6",
  authority_effect: "none",
  source: {
    graph_digest: `sha256:${graphDigest}`,
    content_digest: `sha256:${sha256(contentBytes)}`,
    profile_id: receipt.language.profile_id,
    profile_version: receipt.language.profile_version,
    required_node_ids: [...content.required_system_nodes]
  },
  game: content
};

writeFileSync(outputPath, `// Generated by scripts/build-runtime.mjs; do not hand edit.\nexport const runtimeModel = ${JSON.stringify(model, null, 2)};\n`);
console.log(JSON.stringify({
  status:"PASS",
  output:"web/runtime-model.js",
  graph_digest:model.source.graph_digest,
  rooms:Object.keys(content.rooms).length,
  stations:Object.values(content.rooms).reduce((count, room) => count + room.stations.length, 0),
  puzzles:Object.keys(content.puzzles).length
}, null, 2));

function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}
