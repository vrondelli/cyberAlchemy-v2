import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const runtimeRoot = resolve(scriptDir, "..");
const workspaceRoot = resolve(runtimeRoot, "..");
const nodesPath = resolve(workspaceRoot, "nodes.json");
const relationsPath = resolve(workspaceRoot, "relations.json");
const nodesBytes = readFileSync(nodesPath);
const relationsBytes = readFileSync(relationsPath);
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");
const fail = (code) => { throw new Error(code); };
const requiredNodeFields = ["id", "kind", "label", "status", "meaning", "owner_route", "source_refs", "boundary", "claim_ceiling", "authority_effect"];

const sourceNodes = JSON.parse(nodesBytes).nodes;
const relations = JSON.parse(relationsBytes).relations;
const sourceIds = new Set();
for (const node of sourceNodes) {
  if (sourceIds.has(node.id)) fail(`DUPLICATE_NODE:${node.id}`);
  sourceIds.add(node.id);
  for (const field of requiredNodeFields) if (!(field in node)) fail(`NODE_FIELD_MISSING:${node.id}:${field}`);
  if (node.authority_effect !== "none") fail(`NODE_AUTHORITY_EFFECT:${node.id}`);
}

const relationIds = new Set();
for (const relation of relations) {
  if (relationIds.has(relation.id)) fail(`DUPLICATE_RELATION:${relation.id}`);
  relationIds.add(relation.id);
  if (!relation.source || !relation.target || !relation.type || !relation.claim) fail(`RELATION_FIELD_MISSING:${relation.id}`);
  if (relation.authority_effect !== "none") fail(`RELATION_AUTHORITY_EFFECT:${relation.id}`);
}

const externalIds = [...new Set(relations.flatMap((relation) => [relation.source, relation.target]).filter((id) => !sourceIds.has(id)))].sort();
const externalNodes = externalIds.map((id) => ({
  id,
  kind: "External Reference",
  label: id,
  status: "outside-bounded-source",
  meaning: "The current Workspace relation registry names this endpoint, while its semantic record is owned outside the selected graph source.",
  owner_route: "Owning external source route",
  source_refs: [],
  boundary: "This presentation exposes the endpoint identity and does not infer or import the external record.",
  claim_ceiling: "External relation endpoint identity only.",
  authority_effect: "none",
}));

const graph = {
  graphId: "cyberalchemy-workspace.current-registry-graph",
  sourceEpoch: sha256(Buffer.concat([nodesBytes, Buffer.from([0]), relationsBytes])),
  sourceDigests: { nodes: sha256(nodesBytes), relations: sha256(relationsBytes) },
  authorityEffect: "none",
  nodes: [...sourceNodes, ...externalNodes],
  relations,
};
const output = `/* Generated by scripts/build-workspace-graph.mjs. Do not edit. */\nimport type { WorkspaceGraphSource } from "./graph";\n\nexport const WORKSPACE_GRAPH_SOURCE = ${JSON.stringify(graph, null, 2)} as const satisfies WorkspaceGraphSource;\n`;
const target = resolve(runtimeRoot, "src/features/ontology/graph.generated.ts");
const checkOnly = process.argv.includes("--check");
let current = null;
try { current = readFileSync(target, "utf8"); } catch { /* first materialization */ }
if (checkOnly && current !== output) fail("WORKSPACE_GRAPH_GENERATION_DRIFT");
if (!checkOnly && current !== output) writeFileSync(target, output);
process.stdout.write(`${JSON.stringify({ status: "PASS", mode: checkOnly ? "check" : "write", graphId: graph.graphId, sourceEpoch: graph.sourceEpoch, sourceDigests: graph.sourceDigests, counts: { sourceNodes: sourceNodes.length, externalReferences: externalNodes.length, canvasNodes: graph.nodes.length, relations: relations.length }, authorityEffect: "none" }, null, 2)}\n`);
