import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const runtimeRoot = resolve(scriptDir, "..");
const defaultFoundationRoot = resolve(runtimeRoot, "../../../..", "cyberalchemy-foundation");
const foundationRoot = resolve(process.env.CYBERALCHEMY_FOUNDATION_ROOT || defaultFoundationRoot);
const fail = (code) => { throw new Error(code); };
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

const selected = {
  definitions: "definitions/DEFINITIONS.md",
  capability: "capabilities/foundation/product-capability.json",
  legacyCandidate: "candidates/workbench-definition-projection-v1/candidate.json",
};

const readSelected = (ref) => {
  const path = resolve(foundationRoot, ref);
  const bytes = readFileSync(path);
  return { ref: `foundation://${ref}`, bytes, sha256: sha256(bytes) };
};

const sources = Object.fromEntries(Object.entries(selected).map(([key, ref]) => [key, readSelected(ref)]));
const capability = JSON.parse(sources.capability.bytes.toString("utf8"));
const legacyCandidate = JSON.parse(sources.legacyCandidate.bytes.toString("utf8"));
const definitionsText = sources.definitions.bytes.toString("utf8");

if (capability.authority_effect !== "none" || capability.status !== "candidate") fail("FOUNDATION_CAPABILITY_BOUNDARY_INVALID");
if (legacyCandidate.authority_effect !== "none" || legacyCandidate.product_approval !== "absent") fail("FOUNDATION_CANDIDATE_BOUNDARY_INVALID");
if (legacyCandidate.host_control_plane?.foundation_may_commit_host_state !== false) fail("FOUNDATION_HOST_CUSTODY_INVALID");

const definitions = [];
const definitionPattern = /^## (CAF-D\d+): (.+)\n\nDisposition: ([^\n]+)\n\n([\s\S]*?)(?=\n## CAF-D\d+:|(?![\s\S]))/gm;
for (const match of definitionsText.matchAll(definitionPattern)) {
  const paragraphs = match[4].trim().split(/\n\n+/);
  definitions.push({
    definitionId: match[1],
    title: match[2],
    disposition: match[3],
    summary: paragraphs[0].replace(/\n/g, " "),
    sourceRef: `${sources.definitions.ref}#${match[1]}`,
    sourceSha256: sources.definitions.sha256,
    currentness: "current-at-generated-epoch",
    ownerRoute: "CyberAlchemy Foundation definitions owner; upstream bindings remain candidate",
    boundary: "Workspace projects this candidate definition and does not own, promote, admit, or authorize it.",
    claimCeiling: "Candidate Foundation meaning projected read-only; not CyberAlchemy-v2 canonical vocabulary.",
  });
}
if (definitions.length !== 13) fail(`FOUNDATION_DEFINITION_COUNT_INVALID:${definitions.length}`);

const sourceSet = Object.values(sources).map(({ ref, sha256: digest }) => ({ ref, sha256: digest }));
const sourceEpoch = sha256(Buffer.from(JSON.stringify(sourceSet)));
const snapshot = {
  schemaVersion: "cav2.workspace-foundation-snapshot/v1",
  snapshotId: sha256(Buffer.from(`cav2.workspace.foundation\0${sourceEpoch}`)),
  sourceEpoch,
  generatedAt: "2026-09-03",
  authorityEffect: "none",
  integration: {
    status: "projection-current-host-rebind-required",
    workspaceHostId: "cyberalchemy-v2.workspace.runtime",
    workspaceControlPlane: "workspace.tauri-agent-bridge/candidate",
    foundationMayCommitHostState: false,
    invocationAvailable: false,
    reason: "The available tested Foundation invocation candidate is identity-bound to ide-extension.manual-session-bridge/v2, not this Workspace control plane.",
  },
  capability: {
    capabilityId: capability.capability_id,
    status: capability.status,
    outcome: capability.outcome,
    scope: capability.scope,
    exclusions: capability.exclusions,
    adoptionDecisionState: capability.adoption_decision_state,
    sourceRef: sources.capability.ref,
    sourceSha256: sources.capability.sha256,
  },
  legacyCandidate: {
    candidateId: legacyCandidate.candidate_id,
    status: legacyCandidate.status,
    hostControlPlane: legacyCandidate.host_control_plane.system_of_record,
    claimCeiling: legacyCandidate.claim_ceiling,
    productApproval: legacyCandidate.product_approval,
    sourceRef: sources.legacyCandidate.ref,
    sourceSha256: sources.legacyCandidate.sha256,
  },
  definitions,
  sourceSet,
};

const output = `/* Generated by scripts/build-foundation-snapshot.mjs. Do not edit. */\nimport type { FoundationSnapshot } from "./foundation";\n\nexport const GENERATED_FOUNDATION_SNAPSHOT = ${JSON.stringify(snapshot, null, 2)} as const satisfies FoundationSnapshot;\n`;
const target = resolve(runtimeRoot, "src/domain/foundation.generated.ts");
const checkOnly = process.argv.includes("--check");
let current = null;
try { current = readFileSync(target, "utf8"); } catch {}
if (checkOnly && current !== output) fail("GENERATED_FOUNDATION_SNAPSHOT_DRIFT");
if (!checkOnly && current !== output) writeFileSync(target, output);
process.stdout.write(`${JSON.stringify({ status: "PASS", mode: checkOnly ? "check" : "write", snapshotId: snapshot.snapshotId, sourceEpoch, definitions: definitions.length, authorityEffect: "none" }, null, 2)}\n`);
