// Real browser-local Essays workflow; no native or model dispatch.
// Open questions: T5-RELATIONSHIPS.md#open-questions.
import assert from 'node:assert/strict';
import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {resolve} from 'node:path';
import {startDashboard} from './dashboard-server.mjs';
import {chromium} from '/home/vrondelli/.local/share/are-workspace/browser-tests/node_modules/playwright/index.mjs';
const config=JSON.parse(readFileSync(process.argv[2])),native=JSON.parse(readFileSync(config.console_config));
const out=resolve(process.argv[4]);mkdirSync(out,{recursive:true});
const before=readFileSync(resolve(native.state,'tasks.json'));let app,browser;
try{
 app=await startDashboard({...config,port:0,static_root:resolve(process.argv[3])});
 const data=await (await fetch(app.origin+'/api/v1/workspace/runs')).json(),run=data.projection.runs.find(r=>r.execution==='succeeded');
 browser=await chromium.launch({executablePath:'/home/vrondelli/.cache/ms-playwright/chromium-1243/chrome-linux64/chrome',headless:true});
 const context=await browser.newContext({viewport:{width:1440,height:1000},bypassCSP:true});
 const page=await context.newPage();
 const posts=[],errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/api/**',route=>{if(!['GET','HEAD'].includes(route.request().method())){posts.push(route.request().url());return route.abort();}return route.continue();});
 const read=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('ca2.run-result-handoff.v1')));
 await page.goto(app.origin+'/#/apps/orchestrator/runs/'+encodeURIComponent(run.viewId));
 await page.getByRole('tab',{name:'Result',exact:true}).click();
 await page.getByRole('button',{name:'Open result in Essays',exact:true}).click();
 const panel=page.getByRole('complementary',{name:'Run result handoff',exact:true});await panel.waitFor();
 assert.equal(await panel.getByRole('heading',{name:'Run result → Essays'}).evaluate(el=>document.activeElement===el),true);
 assert.equal((await read()).source.runKey,run.runRef.runKey);assert.equal((await read()).target,null);
 assert.equal(await panel.getByRole('button',{name:'Stage result in editor',exact:true}).isDisabled(),true);
 await page.getByRole('button',{name:'Create local studio',exact:true}).click();
 await page.getByRole('button',{name:'Accept intent',exact:true}).click();
 await page.getByRole('button',{name:'Generate & accept local plan',exact:true}).click();
 const editor=page.locator('[contenteditable="true"]');await editor.waitFor();
 await editor.fill('Existing unsaved writing');
 const savedBefore=await page.evaluate(()=>Object.fromEntries(Object.entries(localStorage).filter(([key])=>key.startsWith('cyberalchemy.essays.workspace.'))));
 await panel.getByRole('checkbox').check();
 await panel.getByRole('button',{name:'Stage result in editor',exact:true}).click();
 await page.waitForFunction(text=>document.querySelector('[contenteditable="true"]')?.textContent===text,run.result.content);
 const staged=await read();assert.ok(staged.target);assert.equal(staged.saved,null);
 const savedAfter=await page.evaluate(()=>Object.fromEntries(Object.entries(localStorage).filter(([key])=>key.startsWith('cyberalchemy.essays.workspace.'))));
 assert.deepEqual(savedAfter,savedBefore,'staging must not save the Essays workspace');
 await page.getByRole('button',{name:'Save accepted draft',exact:true}).click();
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('ca2.run-result-handoff.v1')).saved?.match==='exact');
 await editor.fill('Writer edited this result');
 await page.getByRole('button',{name:'Save accepted draft',exact:true}).click();
 await page.waitForFunction(()=>JSON.parse(localStorage.getItem('ca2.run-result-handoff.v1')).saved?.match==='edited');
 await page.reload();await panel.waitFor();await editor.waitFor();
 assert.equal(await editor.innerText(),'Writer edited this result','reload must not restage captured output');
 assert.equal((await read()).saved.match,'edited');
 await panel.getByRole('link',{name:'Open source run',exact:true}).click();
 await page.getByRole('tab',{name:'Overview',exact:true}).waitFor();
 await page.getByRole('tab',{name:'Result',exact:true}).click();
 await page.getByRole('button',{name:'Open result in Essays',exact:true}).click();
 await page.getByRole('alert').filter({hasText:'already open'}).waitFor();
 assert.equal((await read()).id,staged.id);
 await page.getByRole('button',{name:'Open Essays',exact:true}).click();await panel.waitFor();
 await page.setViewportSize({width:320,height:900});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
 await panel.getByText('Source and target references',{exact:true}).click();
 await page.screenshot({path:resolve(out,'handoff-mobile.png'),fullPage:true});
 await page.addScriptTag({content:readFileSync('/tmp/orchestrator-ux/node_modules/axe-core/axe.min.js','utf8')});
 const axe=await page.evaluate(async()=>{const result=await window.axe.run(document.querySelector('.run-result-handoff'),{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa','wcag22aa']}});return {violations:result.violations,incomplete:result.incomplete};});
 assert.deepEqual(axe.violations,[]);
 const stalePage=await page.context().newPage();
 await stalePage.goto(app.origin+'/#/essays');
 const stalePanel=stalePage.getByRole('complementary',{name:'Run result handoff',exact:true});
 await stalePanel.waitFor();
 await stalePage.locator('[contenteditable="true"]').waitFor();
 await panel.getByRole('button',{name:'Dismiss handoff',exact:true}).click();
 assert.equal(await read(),null);assert.equal(await editor.innerText(),'Writer edited this result');
 await stalePanel.getByRole('checkbox').check();
 await stalePanel.getByRole('button',{name:'Restage result in editor',exact:true}).click();
 await stalePanel.getByText(/Could not update the local handoff/).waitFor();
 assert.equal(await stalePage.locator('[contenteditable="true"]').innerText(),'Writer edited this result');
 assert.equal(await read(),null,'stale tab must not recreate a dismissed handoff');
 await stalePage.close();
 assert.deepEqual(posts,[]);assert.deepEqual(errors,[]);assert.deepEqual(readFileSync(resolve(native.state,'tasks.json')),before);
 writeFileSync(resolve(out,'result.json'),JSON.stringify({status:'PASS',checks:['verified result capture','source owner identity preserved','explicit buffer replacement','staging leaves saved workspace unchanged','exact and edited saves distinguished','reload preserves edited saved draft','return to source run','existing handoff not overwritten','dismiss leaves editor intact','stale tab cannot overwrite newer handoff state','mobile layout','handoff axe scan'],axe,installed_history_unchanged:true,native_launches:0,model_calls:0,open_questions_ref:'T5-RELATIONSHIPS.md#open-questions'},null,2));
 console.log('PASS result → Essays staging → exact/edited save → source run');
}finally{await browser?.close();await app?.close();}
