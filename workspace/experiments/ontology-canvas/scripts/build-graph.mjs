import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const experimentRoot = resolve(scriptDir, "..");
const workspaceRoot = resolve(experimentRoot, "../..");
const experiment = JSON.parse(readFileSync(resolve(experimentRoot, "EXPERIMENT.json"), "utf8"));
const sha256 = (value) => createHash("sha256").update(value).digest("hex");
const fail = (code) => { throw new Error(code); };

const dependencies = new Map(experiment.source_dependencies.map((item) => [item.ref, item]));
const nodesPath = resolve(workspaceRoot, "nodes.json");
const relationsPath = resolve(workspaceRoot, "relations.json");
const nodesBytes = readFileSync(nodesPath);
const relationsBytes = readFileSync(relationsPath);
const nodesDependency = dependencies.get("../../nodes.json");
const relationsDependency = dependencies.get("../../relations.json");

if (!nodesDependency || sha256(nodesBytes) !== nodesDependency.sha256) fail("SOURCE_DIGEST_DRIFT:../../nodes.json");
if (!relationsDependency || sha256(relationsBytes) !== relationsDependency.sha256) fail("SOURCE_DIGEST_DRIFT:../../relations.json");

const sourceNodes = JSON.parse(nodesBytes).nodes;
const relations = JSON.parse(relationsBytes).relations;
const requiredFields = experiment.expected.required_detail_fields;
const sourceIds = new Set();

for (const node of sourceNodes) {
  if (sourceIds.has(node.id)) fail(`DUPLICATE_NODE:${node.id}`);
  sourceIds.add(node.id);
  for (const field of requiredFields) if (!(field in node)) fail(`NODE_FIELD_MISSING:${node.id}:${field}`);
  if (node.authority_effect !== "none") fail(`NODE_AUTHORITY_EFFECT:${node.id}`);
}

const relationIds = new Set();
for (const relation of relations) {
  if (relationIds.has(relation.id)) fail(`DUPLICATE_RELATION:${relation.id}`);
  relationIds.add(relation.id);
  if (relation.authority_effect !== "none") fail(`RELATION_AUTHORITY_EFFECT:${relation.id}`);
}

const externalIds = [...new Set(relations.flatMap((relation) => [relation.source, relation.target]).filter((id) => !sourceIds.has(id)))].sort();
const externalNodes = externalIds.map((id) => ({
  id,
  kind: "External Reference",
  label: id,
  status: "outside-bounded-source",
  meaning: "This relation endpoint is named by the bounded Workspace relation registry but its semantic record is owned outside this experiment's selected node source.",
  owner_route: "Owning external source route",
  source_refs: [],
  boundary: "The canvas exposes the unresolved boundary and does not infer, reconstruct, or import the external record.",
  claim_ceiling: "External relation endpoint identity only.",
  authority_effect: "none",
}));

const graph = {
  experimentId: experiment.experiment_id,
  generatedAt: experiment.fixture_timestamp,
  sourceEpoch: sha256(Buffer.concat([nodesBytes, relationsBytes])),
  sourceDigests: {
    nodes: sha256(nodesBytes),
    relations: sha256(relationsBytes),
  },
  authorityEffect: "none",
  nodes: [...sourceNodes, ...externalNodes],
  relations,
};

if (sourceNodes.length !== experiment.expected.source_node_count) fail("SOURCE_NODE_COUNT_DRIFT");
if (externalNodes.length !== experiment.expected.external_reference_count) fail("EXTERNAL_REFERENCE_COUNT_DRIFT");
if (graph.nodes.length !== experiment.expected.canvas_node_count) fail("CANVAS_NODE_COUNT_DRIFT");
if (relations.length !== experiment.expected.relation_count) fail("RELATION_COUNT_DRIFT");

const target = resolve(experimentRoot, "src/graph.generated.ts");
const output = `/* Generated by scripts/build-graph.mjs. Do not edit. */\nimport type { ExperimentGraphSource } from "./graph";\n\nexport const EXPERIMENT_GRAPH_SOURCE = ${JSON.stringify(graph, null, 2)} as const satisfies ExperimentGraphSource;\n`;
writeFileSync(target, output);

const evidenceRoot = resolve(experimentRoot, "evidence");
mkdirSync(evidenceRoot, { recursive: true });
const receipt = {
  schema_version: "cav2-workspace-ontology-canvas-generation/v1",
  experiment_id: experiment.experiment_id,
  status: "PASS",
  observed_at: new Date().toISOString(),
  fixture_timestamp: graph.generatedAt,
  source_epoch: graph.sourceEpoch,
  source_digests: graph.sourceDigests,
  counts: {
    source_nodes: sourceNodes.length,
    external_references: externalNodes.length,
    canvas_nodes: graph.nodes.length,
    relations: relations.length,
  },
  authority_effect: "none",
  claim_ceiling: experiment.claim_ceiling,
};
writeFileSync(resolve(evidenceRoot, "GENERATION-RECEIPT.json"), `${JSON.stringify(receipt, null, 2)}\n`);
process.stdout.write(`${JSON.stringify(receipt, null, 2)}\n`);
