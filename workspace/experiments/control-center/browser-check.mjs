export default async (page) => {
 const check=(condition,message)=>{if(!condition)throw Error(message);};
 const errors=[];page.on("pageerror",e=>errors.push(e.message));
 await page.getByRole("textbox",{name:"Message",exact:true}).fill("Revise the introduction");
 await page.getByRole("button",{name:"Focus ontology",exact:true}).click();
 check(await page.locator("#target").inputValue()==="essay","Surface selection retargeted draft");
 await page.getByRole("button",{name:"Focus essay",exact:true}).click();
 await page.locator("#suggest").click();
 await page.locator('[data-propose="ontology"]').click();
 check(await page.locator("#essay-panel").getAttribute("class")==="panel primary","Proposal moved panels before Apply");
 await page.locator("#pin").click();
 check(await page.locator("#apply").isDisabled(),"Pin conflict was not blocked");
 await page.locator("#pin").click();
 await page.locator("#apply").click();
 check((await page.locator("#ontology-panel").getAttribute("class")).includes("primary"),"Ontology layout failed");
 check(await page.locator("#draft").inputValue()==="Revise the introduction","Draft lost");
 await page.locator("#restore").click();
 await page.locator("#essay").fill("An edited essay retained across layouts.");
 await page.locator("#expand").click();
 await page.locator("#expand").click();
 check(await page.locator("#draft").inputValue()==="Revise the introduction","Chat resize lost draft");
 await page.locator("#save").click();
 await page.locator("#suggest").click(); await page.locator('[data-propose="orchestration"]').click();await page.locator("#apply").click();
 await page.locator("#load").click();
 check(await page.locator("#essay").inputValue()==="An edited essay retained across layouts.","Layout load undid edits");
 await page.evaluate(()=>{document.querySelector("#essay").focus(); document.querySelector("#trigger-attention").click();});
 check(await page.locator("#essay").evaluate(e=>document.activeElement===e),"Attention stole focus");
 await page.locator("#acknowledge").click();
 check(await page.locator("#attention-state").textContent()==="acknowledged","Acknowledgement incorrect");
 await page.locator("#open-attention").click();await page.locator("#return-work").click();
 check((await page.locator("#essay-panel").getAttribute("class")).includes("primary"),"Return path failed");
 await page.getByRole("button",{name:"Send message",exact:true}).click();
 check(await page.locator("#transcript").textContent().then(t=>t.includes("To The continuity of work")),"Request target missing");
 await page.locator("#expand").click();
 await page.setViewportSize({width:390,height:844});
 const geo=await page.evaluate(()=>{const r=document.querySelector("#chat").getBoundingClientRect();return {bottom:r.bottom,left:r.left,right:r.right,width:innerWidth,height:innerHeight,overflow:document.documentElement.scrollWidth>innerWidth};});
 check(geo.bottom<=geo.height && geo.left>=0 && geo.right<=geo.width && !geo.overflow,"Mobile chat clipped: "+JSON.stringify(geo));
 await page.screenshot({path:"output/playwright/mobile.png"});
 check(errors.length===0,"Browser errors: "+errors.join(","));
 return {result:"PASS",viewport:geo,errors};
};
